// The Template / bind engine — the runtime the generated `view()` imports.
//
// A component compiles (phase 04) to a STATIC SKELETON plus a SLOT TABLE: the
// markup with its dynamic holes emptied, and, for each hole, where it lives
// (an element-child-index `path` from the clone root) and what it is (text /
// attribute / event / two-way / @if / @for). At runtime `view()` does:
//
//   1. instance()      — clone the skeleton into a fresh node tree;
//   2. bind_*_ctx(...)  — wire each slot to a reactive effect (vcsr.signal):
//                         reading a signal subscribes the slot, writing it
//                         re-runs ONLY that slot's patch — O(dependents), no
//                         diff, no virtual DOM;
//   3. view()           — hand back the live root.
//
// THIS FILE holds the backend-NEUTRAL surface (the slot table types + to_str) the
// generated code and both backends share. The rendering backend is selected at
// compile time by the `-d wasm_browser` flag:
//
//   • backend_native_notd_wasm_browser.v — default: an in-memory mock DOM, built
//     with vcsr's own parser, serialized by html() — testable without a browser.
//   • backend_wasm_d_wasm_browser.v      — `-d wasm_browser`: the real DOM via
//     host FFI, holding NO string-keyed maps and not running the V parser (both
//     of which fail on wasm — see docs/WASM-PATHS-ANALYSIS.md §2.1).
//
// Both expose the same Template.instance() / bind_*_ctx / Instance.view() / View,
// so the generated `view()` compiles unchanged against either. Build with
// -enable-globals (the effect stack is global).
module runtime

// SlotKind classifies a dynamic hole. Matches phase 02 / phase 04 exactly.
pub enum SlotKind {
	text    // an element's textContent follows an expression
	attr    // an attribute value follows an expression (`name`)
	event   // a DOM event runs a handler (`name` = event, e.g. 'click')
	bind    // two-way: value follows an expression AND writes back on input
	cond    // @if: an anchor; its row shows while the expression is true (roadmap 4)
	list    // @for: an anchor; a keyed list of rows (roadmap 5)
	toggle  // class:name: class `name` is on while the expression is true
	classes // :class: the classes the expression names, beside the static ones
}

// SlotDesc locates one hole and says what it is. Emitted as a plain const by
// codegen, so every field is pub and the shape is frozen.
pub struct SlotDesc {
pub:
	kind   SlotKind
	path   []int // element-child-index path from the clone root
	anchor int = -1 // >= 0: the slot is the anchor-th comment child of `path` (see slots.anchor_html)
	name   string // attribute name (attr) or event name (event); else ''
}

// Template is a component's compiled form: the static skeleton + the slot table,
// plus its scoped stylesheet, which instance() adds to the page once.
pub struct Template {
pub:
	html  string
	slots []SlotDesc
	css   string
}

__global (
	vcsr_styles []string // the stylesheets added so far, in order
)

// add_style records `css` as added, and reports whether it is new (so the
// backend adds it to the page once, however many instances there are).
fn add_style(css string) bool {
	if css == '' || css in vcsr_styles {
		return false
	}
	vcsr_styles << css
	return true
}

// class_diff lists the classes to remove (in `old`, not in `new`, and not
// `owned`: the element's static classes and class:x names, which :class must
// leave alone) and to add (in `new`, not in `old`) when a `:class` value changes.
fn class_diff(old string, new string, owned string) ([]string, []string) {
	o := old.fields()
	n := new.fields()
	keep := owned.fields()
	return o.filter(it !in n && it !in keep), n.filter(it !in o)
}

// cond_anchor_text and list_anchor_text are what an @if / @for anchor comment
// reads while the runtime cannot render their rows yet (roadmap items 4 and 5):
// the live condition and item count, so the binding is observable on both
// backends (`<!--@if true-->`, `<!--@for 3-->`) and never touches an element.
fn cond_anchor_text(on bool) string {
	return if on { '@if true' } else { '@if false' }
}

fn list_anchor_text(n int) string {
	return '@for ${n}'
}

// to_str renders any bound value to text. Codegen wraps every text/attr/value
// expression in this, so it is a no-op on strings and correct for the scalar
// types bindings use (int/f64/bool). NOTE: a non-scalar operand (a struct/map)
// renders via V's autogenerated debug str() — a multi-line dump in the DOM. The
// intent is that bound expressions are string/numeric; richer types should be
// formatted in the component before binding (a future codegen type-check could
// enforce this).
pub fn to_str[T](v T) string {
	return '${v}'
}
