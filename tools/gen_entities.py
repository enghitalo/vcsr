#!/usr/bin/env python3
"""Regenerate parser/entity_table.v: the HTML5 named character references.

Python's html.entities.html5 is the WHATWG table
(https://html.spec.whatwg.org/entities.json): 2231 names, 106 of them legacy
names that also work without a trailing `;`.

    python3 tools/gen_entities.py > parser/entity_table.v && v fmt -w parser/entity_table.v
"""
from html.entities import html5


def v_string(value: str) -> str:
    out = []
    for ch in value:
        cp = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == "'":
            out.append("\\'")
        elif ch == "$":
            out.append("\\$")
        elif 0x20 <= cp < 0x7F:
            out.append(ch)
        elif cp <= 0xFFFF:
            out.append(f"\\u{cp:04x}")
        else:
            out.append(f"\\U{cp:08x}")
    return "'" + "".join(out) + "'"


names = sorted(html5, key=lambda n: n.encode())
legacy = max(len(n) for n in names if not n.endswith(";"))
print("// The HTML5 named character references, GENERATED by tools/gen_entities.py from")
print("// the WHATWG table (https://html.spec.whatwg.org/entities.json). Do not edit.")
print("//")
print("// Names are without the `&`, sorted by byte for a binary search; a name that")
print("// ends in `;` must be written with it, and the legacy names that also work")
print("// without one (`copy`, `amp`, ...) are listed both ways. Fixed arrays, so they")
print("// are static data rather than a map built at start-up.")
print("module parser")
print()
print(f"// the longest legacy name (one that works without a `;`)")
print(f"const max_legacy_entity_len = {legacy}")
print()
print("const entity_names = [")
for n in names:
    print(f"\t'{n}',")
print("]!")
print()
print("const entity_values = [")
for n in names:
    print(f"\t{v_string(html5[n])},")
print("]!")
